const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { File } = require('node:buffer');
const nodes = Object.fromEntries(['uploadStatus','uploadStatusTitle','uploadStatusDetail','uploadStatusProgress'].map(id => [id,{hidden:true,textContent:'',dataset:{}}]));
const controls = [{disabled:false,isConnected:true},{disabled:true,isConnected:true}];
const window = {clearTimeout(){},setTimeout(){return 1;}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../backend/app/static/admin/admin-uploads.js'),'utf8'), {File,window,document:{getElementById:id=>nodes[id],querySelectorAll:()=>controls}});
const file = new File(['test'],'avatar.png',{type:'image/png'});
const options = {method:'POST',body:{values:()=>[file][Symbol.iterator]()}};
(async()=>{
    let resolve, calls=0;
    const send=()=>{calls++;return new Promise(done=>resolve=done);};
    const first=window.withAdminUpload('/upload',options,send);
    const duplicate=window.withAdminUpload('/upload',options,send);
    assert.equal(calls,1,'repeat requests cannot upload twice');
    assert.equal(first,duplicate);
    assert.equal(controls[0].disabled,true);
    assert.equal(nodes.uploadStatus.hidden,false);
    assert(nodes.uploadStatusTitle.textContent.includes('正在上传'));
    resolve({ok:true}); await first;
    assert.equal(controls[0].disabled,false);
    assert.equal(controls[1].disabled,true,'previously disabled controls stay disabled');
    assert.equal(nodes.uploadStatusTitle.textContent,'上传完成');
    const error=new Error('network interrupted');
    await assert.rejects(window.withAdminUpload('/upload',options,async()=>{throw error;}),error);
    assert.equal(nodes.uploadStatus.dataset.state,'error');
    assert.equal(nodes.uploadStatusDetail.textContent,'network interrupted');
    assert.equal(controls[0].disabled,false);
    await window.withAdminUpload('/upload',options,async()=>({ok:true}));
    assert.equal(nodes.uploadStatus.dataset.state,'done','retry works after failure');
    console.log('PASS immediate upload notice, duplicate suppression, completion, failure, retry and control restoration');
})().catch(error=>{console.error(error);process.exitCode=1;});
