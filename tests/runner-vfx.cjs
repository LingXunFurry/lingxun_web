const assert = require('node:assert/strict');
(async () => {
    const { createRunnerVfx } = await import('../src/lib/runnerVfx.mjs');
    const calls = [], pixels = [];
    const ctx = { save() {}, restore() {}, drawImage(...args) { calls.push(args); }, fillRect(...args) { pixels.push(args); } };
    const fx = createRunnerVfx({ guard: 'guard', wind: 'wind', gust: 'gust' }), player = { xPos: 50, yPos: 140 };
    fx.drawShield(ctx, player, true);
    assert.deepEqual(calls.pop(), ['guard', 52, 136, 40, 40], 'shield is centred on the character');
    assert.equal(calls.length, 4, 'glow follows the shield silhouette, not a full-body ring');
    assert.equal(pixels.length, 8, 'eight sparse pale-blue pixel glints');
    assert(pixels.every(pixel => pixel[2] === 3 && pixel[3] === 3));
    calls.length = pixels.length = 0;
    fx.drawShield(ctx, player, true, true);
    const staticPixels = pixels.slice(); calls.length = pixels.length = 0;
    fx.advance(1000); fx.drawShield(ctx, player, true, true);
    assert.deepEqual(pixels, staticPixels, 'reduced-motion shield has static glints');
    calls.length = pixels.length = 0;
    fx.drawShield(ctx, player, true);
    const paused = calls.slice(); calls.length = 0;
    fx.drawShield(ctx, player, true);
    assert.deepEqual(calls, paused, 'pause does not advance the effect'); calls.length = 0;
    fx.wind(72, 187, 100); fx.drawWind(ctx, 100);
    const initial = calls.pop(); calls.length = 0;
    fx.drawWind(ctx, 120);
    assert.equal(initial[5] - calls.pop()[5], 20, 'wind shares world displacement'); calls.length = 0;
    fx.advance(560); fx.drawWind(ctx, 120);
    assert.equal(calls.length, 0, 'wind expires');
    fx.breakShield(72, 156); fx.drawShield(ctx, player, false);
    assert.equal(calls.length, 2);
    assert(calls.every(call => call[0] === 'guard' && call[3] === 16 && call[4] === 32)); calls.length = 0;
    fx.advance(360); fx.drawShield(ctx, player, false);
    assert.equal(calls.length, 0, 'impact expires');
    fx.wind(72, 187, 100); fx.clear(); fx.drawWind(ctx, 100);
    assert.equal(calls.length, 0, 'restart clears old effects');
    console.log('PASS centred shield, pixel glints, reduced motion, world anchoring, pause, impact and restart');
})().catch(error => { console.error(error); process.exitCode = 1; });
