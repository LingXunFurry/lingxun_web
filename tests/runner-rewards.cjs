const assert = require('node:assert/strict');
(async () => {
    const { DRINKS, advanceRewards, collectDrink, runningFrame, speedMultiplier, approachPace, absorbObstacle } = await import('../src/lib/runnerRewards.mjs');
    const state = { points: 0, remaining: 0 };
    advanceRewards(state, 100, 1000);
    assert.equal(state.points, 100);
    collectDrink(state);
    advanceRewards(state, 100, 1000);
    assert.equal(state.points, 300);
    assert.equal(state.remaining, DRINKS.ale.duration - 1000);
    advanceRewards(state, 800, 8000);
    assert.equal(state.points, 300 + 800 * (1 + (DRINKS.ale.duration - 1000) / 8000));
    assert.equal(state.remaining, 0);
    advanceRewards(state, 100, 1000);
    assert.equal(state.points, 400 + 800 * (1 + (DRINKS.ale.duration - 1000) / 8000));
    assert.equal(runningFrame(0), runningFrame(252));
    assert.equal(runningFrame(126), 16);
    assert.equal(runningFrame(126 * 1.25), 20);
    collectDrink(state, 'ale');
    assert.equal(speedMultiplier(state), 1.12);
    collectDrink(state, 'water');
    assert.equal(state.remaining, DRINKS.ale.duration, 'breeze does not cancel ale');
    assert.equal(state.attraction, DRINKS.water.duration);
    assert.equal(speedMultiplier(state), 1.12);
    assert.equal(state.orders, 1);
    assert.equal(state.deliveries, 0);
    collectDrink(state, 'magic');
    assert.equal(state.shieldTime, DRINKS.magic.duration);
    assert.equal(state.attraction, DRINKS.water.duration, 'shield does not cancel attraction');
    collectDrink(state, 'magic');
    assert.equal(state.shield, 1, 'repeated shield refreshes time, not extra lives');
    assert(absorbObstacle(state));
    assert.equal(state.shield, 0);
    advanceRewards(state, 0, 1100);
    assert(!absorbObstacle(state));
    advanceRewards(state, 0, 13000);
    assert.equal(speedMultiplier(state), 1);
    assert.equal(state.attraction, 0);
    assert.equal(state.shieldTime, 0);
    let pace = 5;
    for (let frame = 0; frame < 1000; frame++) pace = approachPace(pace, 5, 16);
    assert.equal(pace, 5, 'raw pace stays stable before the engine applies mobile scaling');
    for (let frame = 0; frame < 30; frame++) pace = approachPace(pace, 5.75, 16);
    assert.equal(pace, 5.75, 'boost ramps up without overshooting');
    assert(approachPace(pace, 5, 16) > 5, 'boost expires gradually');
    console.log('PASS points / three drinks / delivery bonus / shield / expiry / speed / synchronised frames');
})().catch(error => { console.error(error); process.exitCode = 1; });
